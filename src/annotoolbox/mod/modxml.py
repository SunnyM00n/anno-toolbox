"""Write mod files the Anno 117 mod loader accepts.

Every ``.xml`` inside a mod is read as a patch: it must have a ``ModOps`` root and be well-formed XML. The game's
own config files are neither - they close every element with the shorthand ``</>`` - so a file copied from the game
is rejected twice over (engine-notes "Mod loading, restart, Options"). ``close_tags`` puts the element names back,
``modops`` wraps the result.
"""

from __future__ import annotations

import json
import re

DIFFICULTIES = ("cheat", "easier", "unchanged", "harder")  # modinfo "Difficulty", mandatory in 117
TOKEN = re.compile(r"<[^>]*>")


def modinfo(
    mod_id: str,
    category: str,
    name: str,
    description: str,
    *,
    version: str = "0.1.0",
    safe_to_remove: bool = True,
    requires_new_game: bool = False,
    difficulty: str = "unchanged",
    scripts: dict | None = None,
    load_after: tuple[str, ...] = (),
    setup_flags: dict | None = None,
    dependencies: dict | None = None,
    extra: dict | None = None,
) -> str:
    """The ``modinfo.json`` text of a mod (the loader's fields; English texts only).

    ``difficulty`` is one of ``DIFFICULTIES``; ``Multiplayer`` and ``Campaign`` are always written (true; a mod that
    cannot do either says so in ``setup_flags``, engine-modloader "modinfo.json"). ``load_after``:
    ``Dependencies.LoadAfter``; ``dependencies``: more kinds; ``extra``: more top-level fields, last.
    """
    setup: dict = {"SafeToRemove": safe_to_remove, "Multiplayer": True, "Campaign": True}
    if requires_new_game:
        setup["RequiresNewGame"] = True
    setup.update(setup_flags or {})
    if difficulty not in DIFFICULTIES:
        raise ValueError(f"Difficulty {difficulty!r} is not one of {DIFFICULTIES}")
    fields = {
        "Anno": 8,
        "ModID": mod_id,
        "Version": version,
        "Difficulty": difficulty,
        "GameSetup": setup,
        "Category": {"English": category},
        "ModName": {"English": name},
        "Description": {"English": description},
    }
    if scripts:
        fields["Scripts"] = scripts
    deps = dict(dependencies or {})
    if load_after:
        deps["LoadAfter"] = list(load_after)
    if deps:
        fields["Dependencies"] = deps
    fields.update(extra or {})
    return json.dumps(fields, indent=2) + "\n"


def close_tags(text: str) -> str:
    """Anno's ``</>`` shorthand -> ``</Name>``, so an XML parser takes the fragment."""
    out: list[str] = []
    stack: list[str] = []
    position = 0
    for match in TOKEN.finditer(text):
        out.append(text[position : match.start()])
        position = match.end()
        token = match.group(0)
        if token.startswith(("<!--", "<?", "<![")):
            out.append(token)
        elif token.startswith("</"):
            name = token[2:-1].strip()
            top = stack.pop() if stack else ""
            out.append(f"</{name or top}>")
        elif token.endswith("/>"):
            out.append(token)
        else:
            stack.append(token[1:-1].split()[0])
            out.append(token)
    out.append(text[position:])
    return "".join(out)


def comment_text(text: str) -> str:
    """``text`` for inside an XML comment, which may hold no ``--``: each dash of a run is set apart by a space."""
    while "--" in text:
        text = text.replace("--", "- -")
    return text


def modops(mod_ops: list[str], comment: str = "generated by anno-toolbox") -> str:
    """A ``ModOps`` document around the given operations."""
    return "<ModOps>\n" + f"<!-- {comment_text(comment)} -->\n" + "\n".join(mod_ops) + "\n</ModOps>\n"


SHORTCUT_CONFIG = 2001271  # the ShortcutConfig asset: the game's key bindings
KEY_SESSIONS = "Menu;Session;WorldMap"  # where a binding is active


def shortcut_binding(command: str, key: str, active: str = KEY_SESSIONS) -> str:
    """A key binding that runs the script ``command`` when ``key`` (``Shift;F3``: modifiers, then the key) is pressed
    in the game states ``active``; an ``Add`` of it to ``ShortcutConfig/InputBindings`` at ``SHORTCUT_CONFIG`` puts it
    in the game (engine-modloader, "Reloading while the game runs")."""
    return (
        f"<Item><Command>{command}</Command><Configurable>0</Configurable><Active>{active}</Active>"
        f"<AvailableOnPlatforms>PC</AvailableOnPlatforms><InputTypes><Modern><KeyType>{key}</KeyType></Modern>"
        f"<Legacy><KeyType>{key}</KeyType></Legacy></InputTypes></Item>"
    )


def modop(path: str, payload: str, kind: str = "add") -> str:
    """One operation on the node ``path`` of the patched file (XPath, as the loader takes it)."""
    return f'<ModOp Type="{kind}" Path="{path}">\n{close_tags(payload).strip()}\n</ModOp>'
